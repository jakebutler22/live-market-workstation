import { test, expect } from '@playwright/test'

test('supplied accounting fixture: real HTTP round trip, indicators, signal to later fill, and durable isolation', async ({ page, request }) => {
  const consoleErrors = []
  page.on('pageerror', error => consoleErrors.push(error.message))
  const before = await (await request.get('/api/strategy')).json()
  await page.goto('/', {waitUntil:'domcontentloaded'})
  await expect(page.getByTestId('dataset-select')).toBeEnabled()
  await page.getByTestId('dataset-select').selectOption('worked-eight')
  await page.getByTestId('run-backtest').click()
  await expect(page.getByTestId('account-equity')).toHaveText('990.00')
  await expect(page.getByTestId('account-cash')).toHaveText('990.00')
  await expect(page.getByTestId('account-quantity')).toHaveText('0')
  await page.getByRole('button', { name: /Inspect UP signal/ }).click()
  await expect(page.getByTestId('inspected-fast')).toHaveText('12.5000')
  await expect(page.getByTestId('inspected-slow')).toHaveText('11.0000')
  const trace = page.getByTestId('trace-details')
  await expect(trace).toContainText('BUY 2 · filled')
  await expect(trace).toContainText('14.00 · fee 1.00')
  await expect(trace).toContainText('2 shares · 971.00 cash')
  await trace.getByText('Signal & execution records', {exact:true}).click()
  await expect(trace.getByText('Cost basis after fill', {exact:true})).toBeVisible()
  await expect(trace.getByText('29.00', {exact:true})).toBeVisible()
  await trace.getByText('Signal & execution records', {exact:true}).click()
  await expect(page.locator('canvas').first()).toBeVisible()
  await expect(page.getByText('Worked example · synthetic, not market data')).toBeVisible()
  const id = await page.getByTestId('backtest-id').textContent()
  await page.reload({waitUntil:'domcontentloaded'})
  await page.getByRole('button', {name:'HISTORICAL', exact:true}).click()
  await expect(page.getByTestId('account-equity')).toHaveText('990.00')
  await expect(page.getByTestId('backtest-id')).toHaveText(id)
  const after = await (await request.get('/api/strategy')).json()
  expect(after.paper).toEqual(before.paper)
  expect(consoleErrors).toEqual([])
})

test('genuine recorded history, laptop keyboard focus, and preserved 4.1 replay', async ({ page, request }) => {
  await page.setViewportSize({width:1280,height:800})
  await page.goto('/', {waitUntil:'domcontentloaded'})
  await expect(page.getByTestId('dataset-select')).toBeEnabled()
  await page.getByTestId('dataset-select').selectOption('yahoo-4-1')
  await page.getByTestId('run-backtest').focus()
  await expect(page.getByTestId('run-backtest')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('account-equity')).toHaveText('9,990.75')
  await expect(page.getByTestId('account-quantity')).toHaveText('10')
  await expect(page.getByTestId('signal-row')).toHaveCount(14)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  const run = await (await request.post('/api/backtests',{data:{dataset_id:'yahoo-4-1'}})).json()
  expect(run.dataset.synthetic).toBe(false)
  expect(run.summary.fills).toBe(11)
  expect(run.summary.round_trips).toBe(5)
  await page.getByRole('button', {name:`Inspect UP signal ${run.id}:signal:1794266820:UP`, exact:true}).click()
  const trace = page.getByTestId('trace-details')
  await trace.getByText('Signal & execution records', {exact:true}).click()
  await expect(trace.getByText('59.875', {exact:true})).toBeVisible()
  await expect(trace.getByText('599.75', {exact:true})).toBeVisible()
  await page.getByRole('button',{name:'LIVE',exact:true}).click()
  await expect(page.getByRole('heading',{name:'BHP.AX / Market overview'})).toBeVisible()
  await page.getByRole('button',{name:'REPLAY',exact:true}).click()
  await expect(page.getByRole('button',{name:'Start replay',exact:true})).toBeEnabled()
  await page.getByLabel('Replay speed',{exact:true}).selectOption('60')
  await page.getByRole('button',{name:'Start replay',exact:true}).click()
  await expect(page.getByRole('button',{name:'Pause',exact:true})).toBeVisible()
  await expect(page.getByText('Original recording · UTC')).toBeVisible()
  await expect(page.locator('canvas').first()).toBeVisible()
})
